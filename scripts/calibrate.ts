// npm run calibrate — template calibration report (charging-curve-viewer.md §9, checklist 2.2).
// Reads the data build's car files (run `npm run data:build` first), compares template estimates
// with measured curves and published 10–80 % times, tunes each template, and writes
// docs/plan/calibration-report.md for the owner to approve. It changes no data or code.

import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { TEMPLATES, TEMPLATE_SOC, type TemplateId } from '../src/lib/estimated-curve.ts';
import type { CarDetail } from '../src/lib/types.ts';
import { caseFor, dedupe, estimateMinutes, relError, summarise, tune, type CalibrationCase } from './lib/calibrate.ts';

const carsDir = join(process.cwd(), 'public', 'data', 'cars');
const files: string[] = [];
const walk = (d: string) => {
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (f.endsWith('.json')) files.push(p);
  }
};
walk(carsDir);

const cars: CarDetail[] = files.map((f) => JSON.parse(readFileSync(f, 'utf8')));
const cases = dedupe(cars.map(caseFor).filter((c): c is CalibrationCase => c !== null));
const ids = Object.keys(TEMPLATES) as TemplateId[];
const THIN = 4;

const pct = (x: number) => `${x >= 0 ? '+' : ''}${(x * 100).toFixed(0)} %`;
const min = (x: number) => x.toFixed(1);
const lines: string[] = [];
lines.push('# Template calibration report (checklist 2.2)', '');
lines.push(`Generated by \`npm run calibrate\` on ${new Date().toISOString().slice(0, 10)} from the data build (${cars.length} variants). Target (charging-curve-viewer.md §9): most cars within ±15 % on 10–80 % time.`, '');
lines.push('**How it works.** Each car with a DC peak, a battery size and a reference gets the template estimate (template × DC peak). The reference is its measured curve\'s 10–80 % time (same battery figure), or else its published 10–80 % time. Weights: tested curve 3, community curve 2, published tested 2, published community 1.5, manufacturer curve or claim 1; halved when a measured curve does not cover 10–80 % (B24). Variants with identical inputs and reference count once. Tuning moves the 30/50/70/80 % fractions in 0.01 steps to cut the weighted error (a Huber loss on the log error: squared within ±15 %, linear beyond, so a single odd reference cannot drag a whole template), with a small pull toward the starting shape, keeping the peak at 10 % and the curve falling after it. 0, 10, 90 and 100 % stay as they are (they don\'t change a 10–80 % time).', '');
lines.push('**Error** is the estimate against the reference: +20 % means the estimate is 20 % slower than the reference.', '');

const tuned: Record<TemplateId, number[]> = { ...TEMPLATES };
for (const id of ids) {
  const group = cases.filter((c) => c.template === id);
  tuned[id] = tune(group, TEMPLATES[id]);
}

lines.push('## Summary', '');
lines.push('| Template | Cars | Within ±15 % before | After | Mean abs error before | After | Mean signed before | After |');
lines.push('|---|---|---|---|---|---|---|---|');
for (const id of ids) {
  const group = cases.filter((c) => c.template === id);
  const b = summarise(group, TEMPLATES[id]);
  const a = summarise(group, tuned[id]);
  const thin = group.length < THIN ? ' ⚠ thin' : '';
  lines.push(`| ${id}${thin} | ${b.n} | ${b.within15} | ${a.within15} | ${pct(b.meanAbs).replace('+', '')} | ${pct(a.meanAbs).replace('+', '')} | ${pct(b.meanSigned)} | ${pct(a.meanSigned)} |`);
}
const allB = cases.reduce((n, c) => n + (Math.abs(relError(estimateMinutes(c, TEMPLATES[c.template]), c.refMinutes)) <= 0.15 ? 1 : 0), 0);
const allA = cases.reduce((n, c) => n + (Math.abs(relError(estimateMinutes(c, tuned[c.template]), c.refMinutes)) <= 0.15 ? 1 : 0), 0);
lines.push('', `**All templates:** ${allB} of ${cases.length} within ±15 % before, ${allA} after.`, '');

lines.push('## Proposed template numbers', '');
lines.push(`| SoC | ${ids.map((id) => `${id} (now → proposed)`).join(' | ')} |`);
lines.push(`|---|${ids.map(() => '---').join('|')}|`);
TEMPLATE_SOC.forEach((soc, i) => {
  lines.push(`| ${soc} % | ${ids.map((id) => (TEMPLATES[id][i] === tuned[id][i] ? `${TEMPLATES[id][i].toFixed(2)}` : `${TEMPLATES[id][i].toFixed(2)} → **${tuned[id][i].toFixed(2)}**`)).join(' | ')} |`);
});
lines.push('');

lines.push('## Every calibration car', '');
lines.push('| Variant(s) | Template | DC peak kW | Battery kWh | Reference | Ref 10–80 min | Published | Estimate before | Error | Estimate after | Error |');
lines.push('|---|---|---|---|---|---|---|---|---|---|---|');
for (const c of [...cases].sort((a, b) => a.template.localeCompare(b.template) || a.ids[0].localeCompare(b.ids[0]))) {
  const eb = estimateMinutes(c, TEMPLATES[c.template]);
  const ea = estimateMinutes(c, tuned[c.template]);
  const name = c.ids.length > 1 ? `${c.ids[0]} (+${c.ids.length - 1} same)` : c.ids[0];
  const ref = c.refKind + (c.refExtrapolated ? ' (partly extended)' : '');
  lines.push(`| ${name} | ${c.template} | ${c.dcMaxKw} | ${c.kwh} | ${ref} | ${min(c.refMinutes)} | ${c.published ?? ''} | ${min(eb)} | ${pct(relError(eb, c.refMinutes))} | ${min(ea)} | ${pct(relError(ea, c.refMinutes))} |`);
}
lines.push('');
lines.push('## Notes for the owner', '');
lines.push(`- Groups with fewer than ${THIN} cars are marked ⚠ thin: their tuning rests on very little data.`);
lines.push('- Cars with a measured curve already show that curve; calibration matters for the cars that only have a template.');
lines.push('- "Now" is whatever `TEMPLATES` holds when the script runs; approved numbers go into `TEMPLATES`, charging-curve-viewer.md §9 and gaps-and-questions.md.');

// Cars still outside ±15 % after tuning, for the owner to weigh (§9 step 5: split a template only if a group can't fit).
const misses = cases
  .map((c) => ({ c, e: relError(estimateMinutes(c, tuned[c.template]), c.refMinutes) }))
  .filter((x) => Math.abs(x.e) > 0.15)
  .sort((a, b) => a.e - b.e);
if (misses.length) {
  lines.push(`- Still outside ±15 % after tuning: ${misses.map((x) => `${x.c.ids[0]} (${pct(x.e)}, ${x.c.refKind})`).join('; ')}. A negative error means the template charges faster than the reference.`);
}

const out = join(process.cwd(), 'docs', 'plan', 'calibration-report.md');
writeFileSync(out, lines.join('\n') + '\n');
console.log(`calibration: ${cases.length} cases; within ±15 %: ${allB} → ${allA}. Report: docs/plan/calibration-report.md`);
for (const id of ids) console.log(`  ${id}: ${TEMPLATES[id].join(', ')} → ${tuned[id].join(', ')}`);
