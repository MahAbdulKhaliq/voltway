// `npm run suggest:matches`: for each model in crosswalk/starter-set.json, proposes
// our variants (grouping NRCan rows) and the best OpenEV / Chargeprice matches.
// Writes crosswalk/suggestions.csv (all confirmed=false) and crosswalk/REVIEW.md.
// Nothing here goes live: confirmed rows are copied into crosswalk.csv by a person (1.6).

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { toCsv } from './lib/csv.ts';
import { normalizeMake, parseName, slugify, suggest, tokenize, variantGroupKey, type Candidate, type NrcanTarget } from './lib/match.ts';

const root = process.cwd();
const readDir = (dir: string) =>
  readdirSync(join(root, dir)).filter((f) => f.endsWith('.json')).map((f) => JSON.parse(readFileSync(join(root, dir, f), 'utf8')));

interface StarterModel { make: string; nrcan_model_prefix: string; year: number; our_make: string; our_model: string; name: string }
const starter = JSON.parse(readFileSync(join(root, 'crosswalk', 'starter-set.json'), 'utf8')) as { models: StarterModel[] };

const nrcan: (NrcanTarget & { range_km: { value: number }[] })[] = readDir('data/imported/nrcan').flatMap((f) =>
  f.records.map((r: any) => ({ source_key: r.source_key, year: r.year, make: r.make, model: r.model, motor_kw: r.motor_kw[0].value, range_km: r.range_km })),
);
const openev: Candidate[] = readDir('data/imported/openev').flatMap((f) =>
  f.records.map((r: any) => ({
    source: 'openev', source_key: r.source_key, year: r.year, make: r.make,
    label: [r.model, r.trim, r.variant].filter((x: string | undefined) => x && x !== 'Base').join(' '),
    drivetrain: r.drivetrain, motor_kw: r.motor_kw?.[0]?.value, usable_kwh: r.capacity_usable_kwh?.[0]?.value,
  })),
);
const chargeprice: Candidate[] = readDir('data/imported/chargeprice').flatMap((f) =>
  f.records.map((r: any) => ({
    source: 'chargeprice', source_key: r.source_key, year: r.year, make: r.make,
    label: [r.model, r.variant].filter(Boolean).join(' '),
    usable_kwh: r.capacity_usable_kwh?.[0]?.value, has_curve: Boolean(r.curve),
  })),
);

const csvRows: Record<string, string | number | boolean>[] = [];
const md: string[] = [
  '# Starter set and match review',
  '',
  'Generated by `npm run suggest:matches` from `crosswalk/starter-set.json`. **Nothing here is live.** Suggestions are ranked by name similarity, drivetrain and motor power (vehicle-data-model.md §6). Every row needs a person to confirm it.',
  '',
  'How to review: for each model, check (1) the **proposed variants**, meaning which NRCan rows are the same battery + drivetrain, and (2) the **suggested matches**. Reply with corrections, or "approve all". Confirmed rows are then copied into `crosswalk/crosswalk.csv` with `confirmed=true` in step 1.6.',
  '',
  'Legend: ★ = top suggestion · 📈 = Chargeprice record has a measured curve · ⚠ = needs a careful look',
  '',
];

let variantsTotal = 0;
let unmatchedOpenev = 0;
for (const m of starter.models) {
  const rows = nrcan.filter((r) => r.year === m.year && normalizeMake(r.make) === normalizeMake(m.make) && r.model.startsWith(m.nrcan_model_prefix));
  md.push(`## ${m.year} ${m.make} ${m.name}`, '');
  if (rows.length === 0) { md.push(`⚠ No NRCan rows for ${m.year} ${m.make} "${m.nrcan_model_prefix}…"`, ''); continue; }

  const groups = new Map<string, typeof rows>();
  for (const r of rows) groups.set(variantGroupKey(r), [...(groups.get(variantGroupKey(r)) ?? []), r]);

  const prefixTokens = tokenize(m.nrcan_model_prefix);
  for (const group of groups.values()) {
    variantsTotal++;
    const head = group[0];
    const p = parseName(head.model);
    const rest = p.tokens.slice(prefixTokens.length);
    const slug = [slugify(rest.join(' ')) || (p.drivetrain ?? 'standard'), p.pack_kwh ? `${p.pack_kwh}-kwh`.replace('.', '-') : ''].filter(Boolean).join('-');
    const variantId = `${m.our_make}/${m.our_model}/${m.year}/${slug}`;
    const split = group.length > 1;
    const hints = group.map((r) => {
      const q = parseName(r.model);
      return [q.wheel_in && `${q.wheel_in}" wheels`, q.charger_kw && `${q.charger_kw} kW onboard charger`].filter(Boolean).join(', ');
    });

    md.push(`### \`${variantId}\``, '');
    md.push(`NRCan${split ? ` (${group.length}, proposed as one variant: they differ only by ${[...new Set(hints.filter(Boolean).map((h) => h.replace(/[\d.]+"? ?/, '')))].join(' / ') || 'trim'})` : ''}:`);
    for (const r of group) {
      md.push(`- \`${r.source_key}\` · ${r.range_km[0].value} km · ${r.motor_kw} kW`);
      csvRows.push({ our_variant_id: variantId, source: 'nrcan', source_key: r.source_key, match_method: 'automatic', confirmed: false, score: 1, notes: split ? 'grouped by wheel/charger' : '' });
    }
    if (group.some((r) => parseName(r.model).charger_kw)) {
      md.push('', '⚠ Rows differ by **onboard (AC) charger**. The data model puts `ac_max_kw` on the variant, so one variant can\'t hold both values yet. See the open question at the end.');
    }

    for (const [label, pool] of [['OpenEV Data', openev], ['Chargeprice', chargeprice]] as const) {
      const modelTokens = tokenize(m.nrcan_model_prefix);
      // Show the top match, plus alternatives only when they score close to it.
      const all = suggest(head, pool, 3, modelTokens);
      // Hide alternatives that are just the same car from an older year.
      const seenLabels = new Set<string>();
      const s = all.filter((x, i) => {
        const key = x.candidate.label.toLowerCase();
        if (seenLabels.has(key)) return false;
        seenLabels.add(key);
        return i === 0 || all[0].score - x.score <= 0.1;
      });
      if (s.length === 0) {
        md.push(`- ${label}: *no candidate found*`);
        if (label === 'OpenEV Data') unmatchedOpenev++;
        continue;
      }
      s.forEach((x, i) => {
        const c = x.candidate;
        const extra = [c.usable_kwh && `${c.usable_kwh} kWh`, c.drivetrain, c.has_curve && '📈'].filter(Boolean).join(' · ');
        const warn = x.reasons.some((r) => /differs|not marked AWD$/.test(r)) || x.score < 0.4 ? ' ⚠' : '';
        const lead = i === 0 ? `- ${label}: ★` : '  - or';
        md.push(`${lead} ${c.year} ${c.label} \`${c.source_key}\`${extra ? ` (${extra})` : ''} · score ${x.score}${warn} · ${x.reasons.join('; ')}`);
        if (i === 0) {
          csvRows.push({ our_variant_id: variantId, source: c.source, source_key: c.source_key, match_method: 'automatic', confirmed: false, score: x.score, notes: x.reasons.join('; ') });
        }
      });
    }
    md.push('');
  }
}

md.push(
  '---',
  '',
  '## Open question raised by this review',
  '',
  '**Onboard charger splits.** NRCan rates some cars separately by onboard AC charger (for example Equinox EV AWD and LYRIQ with 11.5 kW or 19.2 kW). By the variant rule (battery, chemistry, DC power or motor layout), these are one variant, but `ac_max_kw` lives on the variant. Proposal: allow `ac_max_kw` on a trim to override the variant, as `range_km` already does. Needs the owner\'s decision before 1.6.',
  '',
);

writeFileSync(join(root, 'crosswalk', 'REVIEW.md'), md.join('\n'));
writeFileSync(
  join(root, 'crosswalk', 'suggestions.csv'),
  toCsv(['our_variant_id', 'source', 'source_key', 'match_method', 'confirmed', 'score', 'notes'], csvRows),
);
console.log(`suggest:matches: ${starter.models.length} models → ${variantsTotal} proposed variants, ${csvRows.length} suggested rows (${unmatchedOpenev} variants with no OpenEV candidate)`);
