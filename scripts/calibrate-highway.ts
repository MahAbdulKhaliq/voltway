// npm run calibrate:highway — highway factor calibration report (route-planner.md §3, R10, B46, B48).
// Reads the data build's car files (run `npm run data:build` first), pairs NRCan highway ratings
// with tested mild-weather highway figures, and writes docs/plan/highway-calibration-report.md for
// the owner to approve. It changes no data or code.

import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { TRIP } from '../src/config.ts';
import type { CarDetail } from '../src/lib/types.ts';
import { bestFactor, errorAt, highwayCase, ratioQuantile, summariseFactor, type HighwayCase } from './lib/calibrate-highway.ts';

const files: string[] = [];
const walk = (d: string) => {
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (f.endsWith('.json')) files.push(p);
  }
};
walk(join(process.cwd(), 'public', 'data', 'cars'));
const cars: CarDetail[] = files.map((f) => JSON.parse(readFileSync(f, 'utf8')));
const cases = cars.map(highwayCase).filter((c): c is HighwayCase => c !== null).sort((a, b) => a.ratio - b.ratio);

const pct = (x: number) => `${x >= 0 ? '+' : ''}${(x * 100).toFixed(0)} %`;
const f2 = (x: number) => x.toFixed(2);
const best = bestFactor(cases);
const options: { label: string; factor: number }[] = [
  { label: `Current placeholder`, factor: TRIP.highwayFactor },
  { label: 'Best fit (geometric mean)', factor: best },
  { label: 'Median', factor: ratioQuantile(cases, 0.5) },
  { label: '75th percentile (conservative)', factor: ratioQuantile(cases, 0.75) },
  { label: '90th percentile (more conservative)', factor: ratioQuantile(cases, 0.9) },
];

const L: string[] = [];
L.push('# Highway factor calibration report (checklist 3.7, R10)', '');
L.push(`Generated by \`npm run calibrate:highway\` on ${new Date().toISOString().slice(0, 10)} from the data build (${cars.length} variants, **${cases.length}** with both an NRCan highway rating and a tested mild-weather highway figure, B48).`, '');
L.push('**What the factor does.** A car with no tested highway figure plans with NRCan highway × factor (route-planner.md §3). The planner turns that into battery % used, so the figure it needs is energy taken **from the battery** at 110–120 km/h.', '');
L.push('**Why it may come out below 1.15.** The 1.15 guess assumed NRCan\'s lab cycle is slower than real highway driving, which is true. But NRCan figures are **wall-side**: they include charging losses (roughly 10–15 %). The tested figures are mostly **battery-side** (the car\'s own display). The two effects partly cancel, and the fitted factor absorbs both.', '');
L.push('**Error** below is NRCan × factor against the tested figure. **+** means the model assumes more energy than the test (the safe side: the car arrives with more battery than planned). **−** means less (the risky side).', '');

L.push('## Options', '');
L.push('| Option | Factor | Mean error (abs) | Cars on the risky side | …by more than 10 % | Worst case |');
L.push('|---|---|---|---|---|---|');
for (const o of options) {
  const s = summariseFactor(cases, o.factor);
  L.push(`| ${o.label} | **${f2(o.factor)}** | ${pct(s.meanAbsError).replace('+', '')} | ${s.under} of ${cases.length} | ${s.underBy10} | ${pct(s.worst)} |`);
}
L.push('');

L.push('## Per car', '');
L.push(`| Car | NRCan hwy (Wh/km) | Tested (Wh/km) | Exact factor | Error at ${f2(TRIP.highwayFactor)} | Error at ${f2(best)} | Tested source |`);
L.push('|---|---|---|---|---|---|---|');
for (const c of cases) {
  L.push(`| ${c.name} | ${c.nrcan.toFixed(0)} | ${c.tested.toFixed(0)} | ${f2(c.ratio)} | ${pct(errorAt(c, TRIP.highwayFactor))} | ${pct(errorAt(c, best))} | \`${c.testedSource}\` |`);
}
L.push('');
L.push('## Caveats', '');
L.push(`- ${cases.length} cars, every tested value \`low_confidence\` (single tests, mostly battery-side, a few rounded). Speeds range from 70 mph (113 km/h) to 120 km/h.`);
L.push('- **Test speed matters.** The 120 km/h tests (Nyland) mostly sit above 1 and the 70 mph (113 km/h) US tests below it. Canadian highway limits are 100–110 km/h, but traffic often runs faster, so a factor a little above the best fit is the honest middle as well as the safer one.');
L.push('- Cars **with** a tested figure plan with it directly; the factor only matters for the others.');
L.push('- Weather, wheels and elevation are handled separately (B48: mild-weather baseline, conservative formulas for the rest).');
L.push('');
L.push('**Owner decision needed:** which factor to ship. On approval: `TRIP.highwayFactor` takes it, `highwayCalibrated` becomes `true` (the "not yet calibrated" warning goes), and route-planner.md §3 and gaps-and-questions record it.');

const out = join(process.cwd(), 'docs', 'plan', 'highway-calibration-report.md');
writeFileSync(out, L.join('\n') + '\n');
console.log(`${cases.length} cases. Best fit ${f2(best)}; median ${f2(ratioQuantile(cases, 0.5))}; p75 ${f2(ratioQuantile(cases, 0.75))}; p90 ${f2(ratioQuantile(cases, 0.9))}. Wrote ${out}`);
