// `npm run gaps`: for every variant, which MVP fields (vehicle-data-model.md §4) are still
// missing once its own values and its confirmed crosswalk matches are counted.
// Writes crosswalk/GAPS.md. Guides hand entry (1.6); the data build (1.7) enforces the result.

import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parseCsv } from './lib/csv.ts';
import { parseName } from './lib/match.ts';

const root = process.cwd();
const listJson = (dir: string): string[] => {
  const out: string[] = [];
  const walk = (d: string) => {
    if (!existsSync(d)) return;
    for (const n of readdirSync(d)) {
      const f = join(d, n);
      if (statSync(f).isDirectory()) walk(f);
      else if (n.endsWith('.json')) out.push(f);
    }
  };
  walk(dir);
  return out.sort();
};
const load = (f: string) => JSON.parse(readFileSync(f, 'utf8'));

// Imported records by source key.
const imported: Record<string, Map<string, any>> = { nrcan: new Map(), openev: new Map(), chargeprice: new Map() };
for (const src of Object.keys(imported)) {
  for (const f of listJson(join(root, 'data/imported', src))) for (const r of load(f).records) imported[src].set(r.source_key, r);
}
const crosswalk = parseCsv(readFileSync(join(root, 'crosswalk/crosswalk.csv'), 'utf8')).filter((r) => r.confirmed === 'true');

// MVP fields and where each can come from. A value counts if it is a non-empty list
// (a sourced value). "unknown" counts as *not yet filled* for this report, so it shows up as a gap.
const VARIANT_FIELDS: { field: string; path: string[]; sources: string[] }[] = [
  { field: 'usable battery', path: ['battery', 'capacity_usable_kwh'], sources: ['openev:capacity_usable_kwh', 'chargeprice:capacity_usable_kwh'] },
  { field: 'chemistry', path: ['battery', 'chemistry'], sources: ['openev:chemistry'] },
  { field: 'voltage class', path: ['battery', 'nominal_voltage_class'], sources: ['openev:nominal_voltage_class', 'chargeprice:nominal_voltage_class'] },
  { field: 'preconditioning', path: ['battery', 'preconditioning'], sources: [] },
  { field: 'AC max kW', path: ['ac_max_kw'], sources: ['openev:ac_max_kw', 'chargeprice:ac_max_kw'] },
  { field: 'DC max kW', path: ['dc_max_kw'], sources: ['openev:dc_max_kw', 'chargeprice:dc_max_kw'] },
  { field: 'charge port', path: ['charge_port'], sources: ['openev:charge_port'] },
  { field: 'Supercharger access', path: ['supercharger_access'], sources: [] },
  { field: 'consumption', path: ['consumption_highway_wh_per_km'], sources: ['nrcan:consumption_highway_wh_per_km'] },
  { field: 'range', path: ['range_km'], sources: ['nrcan:range_km'] },
];
const filled = (v: unknown) => Array.isArray(v) && v.length > 0;
const get = (o: any, path: string[]) => path.reduce((x, k) => (x == null ? undefined : x[k]), o);

const lines: string[] = [
  '# Data gaps (MVP fields still missing)',
  '',
  'Generated by `npm run gaps`. A field is filled when the variant has its own sourced value or a confirmed crosswalk match supplies one. `"unknown"` is listed as a gap here, but it is allowed in the build.',
  '',
];
const totals = new Map<string, number>();
let variantCount = 0;
let complete = 0;
let noCurve = 0; // variants whose only curve is the template estimate (or none, without a DC peak)
let no1080 = 0; // not an MVP field (many makers don't publish one), so it doesn't block "complete"
const byModel = new Map<string, string[]>();
const waiting: string[] = []; // B95: curves with plausibility warnings
for (const f of listJson(join(root, 'data/variants'))) {
  const v = load(f);
  variantCount++;
  const rows = crosswalk.filter((r) => r.our_variant_id === v.id);
  const recs = rows.map((r) => ({ source: r.source, rec: imported[r.source]?.get(r.source_key) })).filter((x) => x.rec);
  const gaps: string[] = [];
  for (const spec of VARIANT_FIELDS) {
    const own = filled(get(v, spec.path));
    const fromSource = spec.sources.some((s) => {
      const [src, key] = s.split(':');
      return recs.some((x) => x.source === src && filled(x.rec[key]));
    });
    if (!own && !fromSource) gaps.push(spec.field);
  }
  if (v.drivetrain === 'unknown') gaps.push('drivetrain');
  const hp = (v.trims ?? []).every((t: any) => filled(t.heat_pump));
  const hpImport = recs.some((x) => x.source === 'openev' && filled(x.rec.heat_pump));
  if (!hp) gaps.push(hpImport ? 'heat pump (OpenEV says standard-or-optional only)' : 'heat pump');
  // Wheels (B14): the trim's own sourced entries, the wheel size in its NRCan row's name, or OpenEV's list.
  const openevWheels = recs.some((x) => x.source === 'openev' && filled(x.rec.wheels));
  const trimHasWheels = (t: any) => {
    if (filled(t.wheels) || openevWheels) return true;
    const row = rows.find((r) => r.source === 'nrcan' && r.our_trim_id === t.id); // same rule as the build
    const rec = row && imported.nrcan.get(row.source_key);
    return Boolean(rec && parseName(rec.model).wheel_in);
  };
  if (!(v.trims ?? []).every(trimHasWheels)) gaps.push('wheel sizes');
  // Curves (B16, B95): read from the built car (run `npm run data:build` first), so the
  // generation rule and the plausibility checks count the way the site applies them.
  const builtFile = join(root, 'public/data/cars', `${v.id}.json`);
  const built = existsSync(builtFile) ? load(builtFile) : { curves: [] };
  const real = (built.curves as any[]).filter((c) => c.kind !== 'estimated' || c.based_on);
  const curveState = real.some((c) => c.kind !== 'estimated') ? 'measured' : real.length ? 'borrowed' : 'template';
  for (const c of real) {
    if (!c.issues?.length) continue;
    const state = c.reviewed_note ? `cleared: ${c.reviewed_note}` : 'waiting for review';
    const list = c.issues.map((i: any) => `${i.level === 'error' ? '❌' : '⚠️'} ${i.message}`).join('; ');
    waiting.push(`- \`${v.id}#${c.id}\` (${c.kind}, ${state}): ${list}`);
  }
  const has1080 = filled(v.published_10_80_min) || recs.some((x) => x.source === 'openev' && filled(x.rec.published_10_80_min));
  for (const g of gaps) totals.set(g, (totals.get(g) ?? 0) + 1);
  if (!has1080) no1080++;
  if (curveState === 'template') noCurve++;
  if (gaps.length === 0) complete++;
  const model = v.model_id;
  const note = [{ measured: '📈 measured curve', borrowed: 'borrowed sibling curve', template: 'template curve only' }[curveState], has1080 ? 'has published 10–80%' : 'no published 10–80%'].join(' · ');
  byModel.set(model, [...(byModel.get(model) ?? []), `- \`${v.id}\` (${note}): ${gaps.length ? gaps.join(', ') : '✅ complete'}`]);
}

lines.push(`**${complete} of ${variantCount} variants complete.** Missing, by field:`, '');
for (const [g, n] of [...totals].sort((a, b) => b[1] - a[1])) lines.push(`- ${g}: ${n}`);
lines.push('', `Also: ${noCurve} of ${variantCount} variants have no measured or borrowed charging curve (template only), and ${no1080} have no published 10–80 % time. Neither blocks "complete", but research should look for both (B15, B16).`, '');
if (waiting.length) {
  lines.push('## Curves with warnings (B95)', '');
  lines.push('A warned curve is the default only once a person clears it: `reviewed_note` on a stored curve, or `"<variant id>#<curve id>": "why it stands"` in `crosswalk/curve-reviews.json` for an imported one.', '');
  lines.push(...waiting, '');
}
for (const [model, items] of byModel) lines.push(`## ${model}`, '', ...items, '');
writeFileSync(join(root, 'crosswalk/GAPS.md'), lines.join('\n'));
console.log(`gaps: ${complete}/${variantCount} variants complete; ${[...totals].map(([g, n]) => `${g} ${n}`).join(' · ')}; template curve only ${noCurve}; no published 10–80% ${no1080}`);
