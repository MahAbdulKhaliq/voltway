// `npm run import:chargeprice`: reads the pinned archive in sources/chargeprice/ and writes
// cars (not motorbikes/microcars), one file per make, to data/imported/chargeprice/<make>.json.
// Also writes data/imported/chargeprice/SKIPPED.md: unflagged generic shapes listed one by one;
// curves Chargeprice itself flags as defaults are counted there and marked `curve_skipped` in the import JSON.

import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { formatJson } from './lib/format-json.ts';
import { join } from 'node:path';
import { makeSlug, normalizeChargeprice, type ChargepriceRecord, type ChargepriceVehicle } from './lib/chargeprice.ts';

const root = process.cwd();
const rawDir = join(root, 'sources', 'chargeprice');
const outDir = join(root, 'data', 'imported', 'chargeprice');

const meta = JSON.parse(readFileSync(join(rawDir, 'FETCHED.json'), 'utf8')) as { file: string; suggested_source_id: string; commit: string };
const sourceId = meta.suggested_source_id;
try {
  readFileSync(join(root, 'data', 'sources', `${sourceId}.json`));
} catch {
  throw new Error(`No source record ${sourceId}. Create data/sources/${sourceId}.json first.`);
}

const archive = JSON.parse(readFileSync(join(rawDir, meta.file), 'utf8')) as { data: ChargepriceVehicle[] };
const cars = archive.data.filter((v) => v.vehicle_type === 'car');

const byMake = new Map<string, ChargepriceRecord[]>();
for (const v of cars) {
  const slug = makeSlug(v.brand);
  byMake.set(slug, [...(byMake.get(slug) ?? []), normalizeChargeprice(v, sourceId)]);
}

mkdirSync(outDir, { recursive: true });
for (const old of readdirSync(outDir)) rmSync(join(outDir, old));
const all: ChargepriceRecord[] = [];
for (const [make, list] of [...byMake].sort(([a], [b]) => a.localeCompare(b))) {
  list.sort((a, b) => a.make.localeCompare(b.make) || a.model.localeCompare(b.model) || a.year - b.year || a.source_key.localeCompare(b.source_key));
  all.push(...list);
  writeFileSync(join(outDir, `${make}.json`), formatJson({ source: 'chargeprice', source_id: sourceId, make, records: list }, { oneLine: 'records' }));
}

const count = (r: ChargepriceRecord['curve_skipped']) => all.filter((x) => x.curve_skipped === r).length;
const kept = all.filter((x) => x.curve).length;
const label = (x: ChargepriceRecord) => `${x.year} ${x.make} ${x.model}${x.variant ? ` (${x.variant})` : ''}`;
const report = [
  '# Chargeprice curves: what was imported and skipped',
  '',
  `Generated by \`npm run import:chargeprice\` from commit \`${meta.commit.slice(0, 7)}\`. Do not edit by hand.`,
  '',
  `- **${kept}** measured curves imported as \`community\` (B95; the build attaches them within the same generation only)`,
  `- **${count('flagged_default')}** skipped: flagged by the archive as a default (generic) curve`,
  `- **${count('generic_shape')}** skipped: not flagged, but a generic template shape (every point below 100% is a round fraction of peak, or fewer than 3 points). See \`isGenericShape\` in scripts/lib/chargeprice.ts`,
  `- **${count('no_curve')}** had no curve`,
  '',
  '## Skipped as generic shape (not flagged by the archive)',
  '',
  ...all.filter((x) => x.curve_skipped === 'generic_shape').map((x) => `- ${label(x)} — \`${x.source_key}\``),
  '',
].join('\n');
writeFileSync(join(outDir, 'SKIPPED.md'), report);

console.log(`import:chargeprice: ${cars.length} cars → ${byMake.size} files; ${kept} curves kept, ${count('flagged_default')} flagged default, ${count('generic_shape')} generic shape`);
